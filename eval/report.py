"""Build eval/report.md from the newest saved runs (numbers are never typed by hand).

  python -m eval.report
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .common import EVAL, RUNS


def latest_with(suite: str, engine_hint: str | None = None) -> tuple[Path, dict[str, Any]] | None:
    for d in sorted(RUNS.iterdir(), reverse=True):
        f = d / "scores.json"
        if not f.exists():
            continue
        s = json.loads(f.read_text(encoding="utf-8"))
        if suite in s and "skipped" not in s[suite]:
            if engine_hint and engine_hint not in json.dumps(s[suite].get("engines", {})):
                continue
            return d, s[suite]
    return None


def pct(x: float | None) -> str:
    return "–" if x is None else f"{x * 100:.0f}%"


def main() -> None:
    out: list[str] = ["# Mathaka evaluation report", "", "_Generated by `python -m eval.report` from `eval/runs/`. Frozen test files are hash-checked before every run._", ""]

    r = latest_with("did_i_take")
    if r:
        d, s = r
        out += [
            "## 1. \"Did I take my medicine?\" + double-dose guard",
            "",
            f"Run `{d.name}`. 40 frozen cases, expected answers written by hand (`eval/sets/did_i_take/cases.jsonl`).",
            "",
            "| Metric | Result |",
            "|---|---|",
            f"| Correct answers | **{s['correct']}/{s['n']}** ({pct(s['accuracy'])}) |",
            f"| Double doses stopped | **{s['double_doses_prevented']}/{s['double_dose_cases']}** |",
            f"| Unsafe elder sentences (\"take another\", doses, mg) | **{len(s['unsafe_answers'])}** |",
            "",
            "Baseline A (plain chat model with no log) needs Gemma via Ollama; see \"Not run yet\" below.",
            "",
        ]

    r = latest_with("pills")
    if r:
        d, s = r
        a, b = s["attributes"], s["baseline_colour_only"]
        out += [
            "## 2. Pill matching (pure TypeScript vision)",
            "",
            f"Run `{d.name}`. {s['photos']} test photos: 6 calibrated pills x 4 photos in new light/angle, plus 3 never-calibrated pills x 4. Note: {s["note"]}.",
            "",
            "| Method | Top-1 on known pills | New-pill rejection |",
            "|---|---|---|",
            f"| Mathaka attributes (shape, size mm, Lab colour, two-tone, score line) + thresholds | **{pct(a['top1_accuracy'])}** | **{pct(a['unknown_rejection_rate'])}** |",
            f"| Baseline B: colour only | {pct(b['top1_accuracy'])} | {pct(b['unknown_rejection_rate'])} |",
            "",
            f"Wrong-pill answers: {a['wrong_pill']}; unsure -> asked a human: {a['unsure_to_human']}. Median time per photo on the laptop (Node): {s['median_ms_node']} ms.",
            "",
        ]

    r = latest_with("intents", "laya")
    if r:
        d, s = r
        out += [
            "## 3. Decision layer (\"the AI that is not allowed to speak\")",
            "",
            f"Run `{d.name}`, set `{s['set']}` ({s['n']} lines). **This is the dev set written by Claude, not the frozen family-written test.**",
            "",
            "| Engine | Accuracy | si | Singlish | en | mixed | ECE | Escalated | **Wrong action** | Median ms (laptop CPU) |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for name, e in s["engines"].items():
            a = e["all"]
            f = a["accuracy_by_form"]
            out.append(
                f"| {name} | {pct(a['accuracy'])} | {pct(f.get('si'))} | {pct(f.get('singlish'))} | {pct(f.get('en'))} | {pct(f.get('mixed'))} | {a['ece']} | {pct(a['escalation_rate'])} | **{pct(a['wrong_action_rate'])}** | {a['latency_ms_median']} |"
            )
        out += [
            "",
            "Threshold 0.85. \"Wrong action\" = the engine was confident (≥ threshold), picked an acting label (not `other` / `unsure`), and was wrong. That is the number that matters most for a vulnerable person.",
            "",
            "**Gate result: Laya is NOT the default yet.** Zero-shot Laya does well on English, but on Sinhala script and Singlish it is far below what we need. The multilingual checkpoint acts wrongly too often. The elder phone therefore keeps the buttons-only RuleEngine (0% wrong actions by design), and Laya waits for the Sinhala fine-tune (`eval/finetune/`).",
            "",
        ]

    out += [
        "## Not run yet (needs hardware or data)",
        "",
        "- **Gemma** (prescription extraction, decision baseline, Baseline A): needs Ollama + `gemma3:4b` on the laptop, or the on-device build.",
        "- **Real pill photos** and the **family-written frozen intents test**: being collected (`eval/sets/*/README.md`).",
        "- **On-phone latency and memory**: Family → More → Benchmark, screenshot on a new and an old phone.",
        "- **Real users**: 1–3 family elders, with consent (`docs/accessibility-checklist.md`).",
        "",
    ]
    (EVAL / "report.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {EVAL / 'report.md'}")


if __name__ == "__main__":
    main()
